"""Regenerates tools.ts (the Tools reference) from the MCP server's source.

    python3 src/docs/gen_tools.py ../orilos-backed/src/orilos_mcp/server.py
"""

import ast
import json
import re
import sys
from pathlib import Path


def dashless(t: str) -> str:
    """The docs never show em/en dashes: ranges read "2 to 5", a clause break becomes a new sentence."""
    t = re.sub(r"(\d)\s*[–—]\s*(\d)", r"\1 to \2", t)
    t = re.sub(r"\s+[—–]\s+(\S)", lambda m: ". " + m.group(1).upper(), t)
    t = re.sub("[\U0001F000-\U0001FFFF\u2600-\u27BF]\ufe0f?", "<emoji>", t)  # no emoji in the docs
    return t.replace("—", ", ").replace("–", "-")

src = Path(sys.argv[1]).read_text(encoding="utf-8")
tree = ast.parse(src)


def text(node) -> str:
    return ast.get_source_segment(src, node) if node is not None else ""


tools, pick = [], []
for node in tree.body:
    if isinstance(node, ast.AsyncFunctionDef | ast.FunctionDef) and any("mcp.tool" in text(d) for d in node.decorator_list):
        args = node.args.args
        defaults = [None] * (len(args) - len(node.args.defaults)) + list(node.args.defaults)
        params = [{"name": a.arg, "type": text(a.annotation), "default": text(d) if d is not None else None}
                  for a, d in zip(args, defaults) if text(a.annotation) != "Context"]
        doc = dashless(ast.get_docstring(node) or "")
        ret = text(node.returns)
        tools.append({"name": node.name, "doc": doc, "params": params, "returns": ret})
    if isinstance(node, ast.ClassDef) and node.name == "ClipPick":
        for f in node.body:
            if isinstance(f, ast.AnnAssign):
                call = f.value
                desc, default = "", None
                if isinstance(call, ast.Call):
                    for kw in call.keywords:
                        if kw.arg == "description":
                            desc = ast.literal_eval(kw.value) if not isinstance(kw.value, ast.JoinedStr) else text(kw.value)
                        if kw.arg == "default_factory":
                            default = text(kw.value) + "()"
                    if call.args:
                        default = text(call.args[0])
                pick.append({"name": f.target.id, "type": text(f.annotation), "default": default, "description": dashless(desc)})

# The pro-edit presets, if this version has them (edit.py next to server.py).
edit_styles = {}
edit_py = Path(sys.argv[1]).with_name("edit.py")
if edit_py.exists():
    for node in ast.parse(edit_py.read_text(encoding="utf-8")).body:
        if isinstance(node, ast.AnnAssign | ast.Assign):
            target = node.target if isinstance(node, ast.AnnAssign) else node.targets[0]
            if getattr(target, "id", "") == "STYLES":
                edit_styles = ast.literal_eval(node.value)

out = Path(__file__).with_name("tools.ts")
out.write_text(
    "// Generated by gen_tools.py from orilos-mcp's server.py. Don't edit by hand: re-run the generator.\n\n"
    "export interface Param { name: string; type: string; default: string | null }\n"
    "export interface Tool { name: string; doc: string; params: Param[]; returns: string }\n"
    "export interface PickField { name: string; type: string; default: string | null; description: string }\n\n"
    f"export const TOOLS: Tool[] = {json.dumps(tools, indent=2, ensure_ascii=False)};\n\n"
    f"export const CLIP_PICK: PickField[] = {json.dumps(pick, indent=2, ensure_ascii=False)};\n\n"
    "// Pro-edit presets from edit.py (empty when this version has none).\n"
    f"export const EDIT_STYLES: Record<string, Record<string, string | number | boolean>> = {json.dumps(edit_styles, indent=2)};\n",
    encoding="utf-8")
print(f"{len(tools)} tools, {len(pick)} ClipPick fields, {len(edit_styles)} edit styles -> {out}")
